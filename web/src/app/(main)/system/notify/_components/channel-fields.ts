// parseKV parses a textarea of "KEY=VALUE" lines.
export function parseKV(text: string): Record<string, string> {
  const out: Record<string, string> = {};
  for (const line of text.split("\n")) {
    const t = line.trim();
    if (!t) continue;
    const i = t.indexOf("=");
    if (i > 0) out[t.slice(0, i).trim()] = t.slice(i + 1).trim();
  }
  return out;
}
// parseIDs parses an id list separated by commas/whitespace.
export function parseIDs(text: string): number[] {
  return text
    .split(/[\s,\uff0c]+/)
    .map((s) => s.trim())
    .filter(Boolean)
    .map((s) => Number(s))
    .filter((n) => Number.isFinite(n) && n > 0);
}
// parseKeywords parses a keyword list separated by lines/commas (vulnerability type names may contain spaces, so it splits on lines or commas).
export function parseKeywords(text: string): string[] {
  return text
    .split(/[\n,\uff0c]+/)
    .map((s) => s.trim())
    .filter(Boolean);
}
