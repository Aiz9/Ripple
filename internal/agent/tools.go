// intentItem represents one direction in single/batch add_intent.
type intentItem struct {
	Summary   string            `json:"summary"`
	AssetIDs  []json.RawMessage `json:"asset_ids"`
	ParentIDs []json.RawMessage `json:"parent_ids"`
	Priority  int               `json:"priority"`
	// Unit of work: one vulnerability class on one component, with 1-3 worker skills.
	VulnClass string   `json:"vuln_class"`
	Component string   `json:"component"`
	Skills    []string `json:"skills"`
}

// maxIntentSkills keeps each worker specialised (strix: 1-3 skills per agent).
const maxIntentSkills = 3

// addOneIntent creates an intent, links upstream lineage, and returns its ID.
// Every parent_id must be an existing confirmed fact/finding, never an intent/goal/hint.
// Empty parent_ids for new top-level directions fall back to the origin fact.
// The creation path enforces fact-anchored, discovery-driven intent generation.
func (t *ToolSet) addOneIntent(it intentItem) (int64, error) {
	if strings.TrimSpace(it.Summary) == "" {
		return 0, fmt.Errorf("summary must not be empty")
	}
	// Validate anchors before creation to avoid orphan intents on invalid input.
	parents := pidList(it.ParentIDs)
	for _, pidv := range parents {
		n, err := t.ts.GetNodeWithSources(pidv)
		if err != nil || n == nil {
			return 0, fmt.Errorf("parent_id %d does not exist in this task or directly related tasks: parent_ids must be existing fact/finding node IDs; leave parent_ids empty for new top-level directions", pidv)
		}
		if n.Kind != db.KindFact && n.Kind != db.KindFinding {
			return 0, fmt.Errorf("parent_id %d is a %q node and cannot anchor an intent: only confirmed fact/finding nodes are allowed, not intents/goals/hints; leave parent_ids empty for new top-level directions", pidv, n.Kind)
		}
	}
	if len(it.Skills) > maxIntentSkills {
		return 0, fmt.Errorf("skills: at most %d per intent — split the work into more specialised intents", maxIntentSkills)
	}
	if WorkerSkillNames != nil && len(it.Skills) > 0 {
		known := map[string]bool{}
		for _, n := range WorkerSkillNames() {
			known[n] = true
		}
		for _, sk := range it.Skills {
			if !known[sk] {
				return 0, fmt.Errorf("skill %q is not available to workers; available: %s", sk, strings.Join(WorkerSkillNames(), ", "))
			}
		}
	}
	priority := it.Priority
	if priority == 0 {
		priority = 5
	}
	anchors := pidList(it.AssetIDs)
	// Do not dispatch an intent whose bound assets match asset-interception rules.
	if t.as != nil && len(anchors) > 0 {
		hits, err := t.as.CheckAssetsIntercept(t.taskID, anchors)
		if err != nil {
			return 0, fmt.Errorf("Asset interception validation failed: %w", err)
		}
		if len(hits) > 0 {
			var b strings.Builder
			fmt.Fprintf(&b, "Assets bound to intent '%s' failed testing-scope validation; stop testing these assets: ", it.Summary)
			for _, h := range hits {
				fmt.Fprintf(&b, "\n - %s", h.Describe())
			}
			return 0, fmt.Errorf("%s", b.String())
		}
	}
	payload := map[string]any{"summary": it.Summary}
	if v := strings.TrimSpace(it.VulnClass); v != "" {
		payload["vuln_class"] = v
	}
	if v := strings.TrimSpace(it.Component); v != "" {
		payload["component"] = v
	}
	if len(it.Skills) > 0 {
		payload["skills"] = it.Skills
	}
	if len(anchors) > 0 {
		payload["asset_ids"] = anchors
	}
	id, err := t.ts.AddIntent(payload, priority, anchors, "planner")
	if err != nil {
		return 0, err
	}
	// upstream lineage: link each (validated) fact/finding parent → this intent, so
	// "multiple facts combine into one new intent" is expressible.
	for _, parent := range parents {
		_ = t.ts.Link(parent, db.RelDerivedFrom, id)
	}
	// a top-level intent (no explicit parent) connects to the origin fact, so every
	// intent still traces back to a fact node — at task start the only fact is the
	// origin, and the first intents derive from it.
	if len(parents) == 0 {
		if origin, _ := t.ts.OriginFactID(); origin > 0 {
			_ = t.ts.Link(origin, db.RelDerivedFrom, id)
		}
	}
	return id, nil
}

