func (t *ToolSet) proveGoal() actool.CoreTool {
	return t.writeExpTool("prove_goal", "Call when a finding/fact proves a goal: connect the evidence node to the goal and mark it met.",
		obj(map[string]any{
			"goal_id":        idp("Goal node ID"),
			"evidence_id":    idp("Finding/fact node ID proving the goal"),
			"reason":         str("Why this evidence satisfies the goal"),
			"chain_analysis": str("Required when proving the LAST open goal with 2+ confirmed findings: which findings could chain into a higher-impact path, which chains were tested (and filed if they worked), why the rest are unrelated"),
		}, "goal_id", "evidence_id"),
		func(ctx context.Context, in json.RawMessage) (actool.Result, error) {
			var a struct {
				GoalID        json.RawMessage `json:"goal_id"`
				EvidenceID    json.RawMessage `json:"evidence_id"`
				Reason        string          `json:"reason"`
				ChainAnalysis string          `json:"chain_analysis"`
			}
			_ = json.Unmarshal(in, &a)
			goal, ev := pid(a.GoalID), pid(a.EvidenceID)
			if goal == 0 || ev == 0 {
				return actool.Errorf("goal_id and evidence_id are required"), nil
			}
			goalNode, err := t.ts.GetNode(goal)
			if err != nil || goalNode == nil || goalNode.Kind != db.KindGoal {
				return actool.Errorf("goal_id must be a goal in this task (related-task goals are read-only)"), nil
			}
			evidenceNode, err := t.ts.GetNodeWithSources(ev)
			if err != nil || evidenceNode == nil || (evidenceNode.Kind != db.KindFact && evidenceNode.Kind != db.KindFinding) {
				return actool.Errorf("evidence_id must be a fact/finding node in this task or a directly related task"), nil
			}
			if evidenceNode.Kind == db.KindFinding && evidenceNode.State != "confirmed" {
				return actool.Errorf("evidence_id is a withdrawn/dismissed finding and cannot prove a goal"), nil
			}
			// Finish gate: proving the last open goal completes the task, so it must not
			// leave live intents, owed follow-ups or unconsidered chains behind. The final
			// timeout round is exempt: nothing can be dispatched any more.
			if goalNode.State == "open" && !taskClockFrom(ctx).Final && t.isLastOpenGoal(goal) {
				if msg := t.finishGate(a.ChainAnalysis); msg != "" {
					return actool.Errorf(msg), nil
				}
			}
			_ = t.ts.Link(ev, db.RelProves, goal)
			_ = t.ts.SetNodeState(goal, "met")
			// After each goal becomes met, check all task goals and automatically set GoalMet when complete,
			// without requiring an explicit model call to goal_met.
			if goals, err := t.ts.ListByKind(db.KindGoal, 1000); err == nil && len(goals) > 0 {
				allMet := true
				for _, g := range goals {
					if g.State != "met" {
						allMet = false
						break
					}
				}
				if allMet {
					t.GoalMet = true
					t.Reason = fmt.Sprintf("All %d goals are met (last triggered by goal %d)", len(goals), goal)
					if ca := strings.TrimSpace(a.ChainAnalysis); ca != "" {
						t.Reason += "; chain analysis: " + ca
					}
					return actool.Text(fmt.Sprintf("goal %d marked met; all task goals achieved, task automatically completed", goal)), nil
				}
			}
			return actool.Text(fmt.Sprintf("goal %d marked met", goal)), nil
		})
}

